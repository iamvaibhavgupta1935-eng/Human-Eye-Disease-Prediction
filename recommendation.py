# Recommendation for each disease class

cnv = """**For CNV (Choroidal Neovascularization)**:
- Immediate consultation with a retinal specialist
- Anti-VEGF injections recommended (Ranibizumab, Aflibercept)
- Regular OCT monitoring every 1–3 months
- Maintain healthy diet rich in antioxidants
"""

dme = """**For DME (Diabetic Macular Edema)**:
- Control blood sugar and blood pressure
- Anti-VEGF therapy as primary treatment
- Regular eye checkups (3–6 months)
- Consult both ophthalmologist and endocrinologist
"""

drusen = """**For Drusen (Early AMD)**:
- Use AREDS2 supplements if advised
- Maintain antioxidant-rich diet
- Avoid smoking
- Regular monitoring (6–12 months)
"""

normal = """**For Normal Retina**:
- Routine eye checkups every 1–2 years
- Maintain healthy lifestyle
- Protect eyes from UV exposure
"""